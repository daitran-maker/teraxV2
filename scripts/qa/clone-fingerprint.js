#!/usr/bin/env node
/**
 * QA - Clone fidelity fingerprint.
 * Fingerprints a database that was created the same way a tenant clone is
 * (empty DB + init.sql + app startup migrations/seeds), so we can prove that a new clone
 * after a refactor is identical to a clone made by the pre-refactor code.
 *
 *   DATABASE_URL=postgres://.../db node scripts/qa/clone-fingerprint.js out.json
 *   node scripts/qa/clone-fingerprint.js --diff a.json b.json
 *
 * Captures: columns (name/type/default/nullable), views, indexes, triggers, functions, sequences,
 * constraints, and per-table row count + md5 of row content (volatile columns excluded).
 */
const fs = require('fs');
const crypto = require('crypto');

const VOLATILE = /(^|_)(created|updated|deleted|modified|last|login|logged|synced|expires?|timestamp|date|time)(_|$)|_at$|^log$|^logs$|^id$|token|password|hash|uuid/i;

async function fingerprint(pool) {
  const q = async (sql) => (await pool.query(sql)).rows;
  const fp = { columns: {}, views: {}, indexes: [], triggers: [], functions: [], sequences: [], constraints: [], tables: {}, functionDefs: {} };

  for (const r of await q(`select table_name, column_name, data_type, is_nullable, column_default
      from information_schema.columns where table_schema='public' order by table_name, ordinal_position`)) {
    (fp.columns[r.table_name] = fp.columns[r.table_name] || []).push(
      `${r.column_name}|${r.data_type}|${r.is_nullable}|${(r.column_default || '').replace(/nextval\('[^']*'/, "nextval('<seq>'")}`
    );
  }
  for (const r of await q(`select viewname, md5(definition) h from pg_views where schemaname='public' order by 1`)) fp.views[r.viewname] = r.h;
  fp.indexes = (await q(`select indexdef from pg_indexes where schemaname='public' order by indexname`)).map((r) => r.indexdef);
  fp.triggers = (await q(`select tgname||' on '||tgrelid::regclass::text||' '||md5(pg_get_triggerdef(oid)) t from pg_trigger where not tgisinternal order by 1`)).map((r) => r.t);
  fp.functions = (await q(`select p.proname||' '||md5(replace(pg_get_functiondef(p.oid), E'\\r', '')) f from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' order by 1`)).map((r) => r.f);
  for (const r of await q(`select p.proname n, pg_get_functiondef(p.oid) d from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public'`)) fp.functionDefs[r.n] = r.d;
  fp.sequences = (await q(`select sequencename from pg_sequences where schemaname='public' order by 1`)).map((r) => r.sequencename);
  fp.constraints = (await q(`select conrelid::regclass::text||' '||conname||' '||pg_get_constraintdef(oid) c from pg_constraint where connamespace='public'::regnamespace order by 1`)).map((r) => r.c);

  for (const t of Object.keys(fp.columns)) {
    const isTable = (await q(`select 1 from information_schema.tables where table_schema='public' and table_name='${t}' and table_type='BASE TABLE'`)).length;
    if (!isTable) continue;
    const cols = fp.columns[t].map((c) => c.split('|')[0]).filter((c) => !VOLATILE.test(c));
    const count = (await q(`select count(*)::int c from "${t}"`))[0].c;
    let hash = 'n/a';
    // audit_logs content is generated by triggers during startup and differs between runs of identical code
    if (cols.length && count <= 20000 && t !== 'audit_logs') {
      const rows = await q(`select md5(coalesce(string_agg(r, E'\\n' order by r), '')) h from (select concat_ws('|', ${cols.map((c) => `"${c}"::text`).join(',')}) r from "${t}") x`);
      hash = rows[0].h;
    }
    fp.tables[t] = { count, hash };
  }
  return fp;
}

function diff(a, b) {
  const out = [];
  const cmpList = (name, x, y) => {
    const sx = new Set(x), sy = new Set(y);
    for (const v of sx) if (!sy.has(v)) out.push(`${name}: only in A: ${v.slice(0, 160)}`);
    for (const v of sy) if (!sx.has(v)) out.push(`${name}: only in B: ${v.slice(0, 160)}`);
  };
  const tables = new Set([...Object.keys(a.columns), ...Object.keys(b.columns)]);
  for (const t of tables) {
    if (!a.columns[t]) { out.push(`table only in B: ${t}`); continue; }
    if (!b.columns[t]) { out.push(`table only in A: ${t}`); continue; }
    cmpList(`columns(${t})`, a.columns[t], b.columns[t]);
  }
  const vn = new Set([...Object.keys(a.views), ...Object.keys(b.views)]);
  for (const v of vn) if (a.views[v] !== b.views[v]) out.push(`view differs: ${v}`);
  cmpList('indexes', a.indexes, b.indexes); cmpList('triggers', a.triggers, b.triggers);
  cmpList('functions', a.functions, b.functions); cmpList('sequences', a.sequences, b.sequences);
  cmpList('constraints', a.constraints, b.constraints);
  const tn = new Set([...Object.keys(a.tables), ...Object.keys(b.tables)]);
  for (const t of tn) {
    const x = a.tables[t], y = b.tables[t];
    if (!x || !y) continue;
    if (x.count !== y.count) out.push(`rows(${t}): ${x.count} vs ${y.count}`);
    else if (x.hash !== y.hash) out.push(`row content differs: ${t} (count ${x.count})`);
  }
  return out;
}

(async () => {
  const args = process.argv.slice(2);
  if (args[0] === '--diff') {
    const a = JSON.parse(fs.readFileSync(args[1], 'utf8')), b = JSON.parse(fs.readFileSync(args[2], 'utf8'));
    const d = diff(a, b);
    if (d.length) { console.error(`DIFFERENT (${d.length}):\n` + d.join('\n')); process.exit(1); }
    console.log(`IDENTICAL: ${Object.keys(a.tables).length} tables, ${a.indexes.length} indexes, ${a.triggers.length} triggers, ${a.functions.length} functions.`);
    return;
  }
  const { Pool } = require('pg');
  const pool = new Pool({ connectionString: process.env.DATABASE_URL });
  const fp = await fingerprint(pool);
  await pool.end();
  fs.writeFileSync(args[0] || 'fingerprint.json', JSON.stringify(fp, null, 1));
  const rows = Object.values(fp.tables).reduce((s, t) => s + t.count, 0);
  console.log(`Fingerprint: ${Object.keys(fp.tables).length} tables, ${rows} rows total -> ${args[0] || 'fingerprint.json'}`);
})().catch((e) => { console.error(e.message); process.exit(1); });
